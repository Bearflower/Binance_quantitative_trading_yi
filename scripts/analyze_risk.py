#!/usr/bin/env python3
"""分析MTPCS策略的盈亏比和风险控制"""

# 策略配置参数
config = {
    '止损ATR倍数': 2.0,
    '止盈TP1_ATR倍数': 2.5,
    '止盈TP1平仓比例': 0.25,
    '止盈TP2_ATR倍数': 4.0,
    '止盈TP2平仓比例': 0.25,
    '剩余仓位比例': 0.50,
    '吊灯止损启动阈值': 1.8,
    '吊灯止损回撤阈值': 1.2,
}

print("\n" + "="*70)
print("MTPCS策略盈亏比分析")
print("="*70)

# 1. 基础盈亏比分析
print("\n【一、基础盈亏比】")
止损距离 = config['止损ATR倍数']
止盈TP1距离 = config['止盈TP1_ATR倍数']
止盈TP2距离 = config['止盈TP2_ATR倍数']

盈亏比_TP1 = 止盈TP1距离 / 止损距离
盈亏比_TP2 = 止盈TP2距离 / 止损距离

print(f"止损距离: {止损距离}×ATR")
print(f"止盈TP1距离: {止盈TP1距离}×ATR")
print(f"止盈TP2距离: {止盈TP2距离}×ATR")
print(f"\n盈亏比分析:")
print(f"  TP1盈亏比: {盈亏比_TP1:.2f} (盈利{止盈TP1距离}ATR vs 亏损{止损距离}ATR)")
print(f"  TP2盈亏比: {盈亏比_TP2:.2f} (盈利{止盈TP2距离}ATR vs 亏损{止损距离}ATR)")

# 2. 分批止盈的综合盈亏比
print("\n【二、分批止盈综合盈亏比】")
TP1盈利 = 止盈TP1距离 * config['止盈TP1平仓比例']
TP2盈利 = 止盈TP2距离 * config['止盈TP2平仓比例']
剩余仓位盈利 = 止盈TP2距离 * config['剩余仓位比例']  # 假设剩余仓位也在TP2平仓

总盈利 = TP1盈利 + TP2盈利 + 剩余仓位盈利
综合盈亏比 = 总盈利 / 止损距离

print(f"TP1盈利贡献: {止盈TP1距离}ATR × {config['止盈TP1平仓比例']*100}% = {TP1盈利:.2f}ATR")
print(f"TP2盈利贡献: {止盈TP2距离}ATR × {config['止盈TP2平仓比例']*100}% = {TP2盈利:.2f}ATR")
print(f"剩余仓位盈利贡献: {止盈TP2距离}ATR × {config['剩余仓位比例']*100}% = {剩余仓位盈利:.2f}ATR")
print(f"\n综合盈利: {总盈利:.2f}ATR")
print(f"综合盈亏比: {综合盈亏比:.2f}")

# 3. 胜率要求分析
print("\n【三、盈亏平衡胜率要求】")
for 盈亏比 in [盈亏比_TP1, 盈亏比_TP2, 综合盈亏比]:
    盈亏平衡胜率 = 1 / (1 + 盈亏比) * 100
    print(f"盈亏比 {盈亏比:.2f} 需要胜率: {盈亏平衡胜率:.1f}%")

# 4. 不同胜率下的期望收益
print("\n【四、不同胜率下的期望收益（每ATR）】")
print(f"{'胜率':<10} {'TP1止盈':<15} {'TP2止盈':<15} {'综合止盈':<15}")
print("-" * 60)
for 胜率 in [0.30, 0.35, 0.40, 0.45, 0.50, 0.55, 0.60]:
    胜率_pct = 胜率 * 100
    败率 = 1 - 胜率
    
    期望_TP1 = 胜率 * 止盈TP1距离 - 败率 * 止损距离
    期望_TP2 = 胜率 * 止盈TP2距离 - 败率 * 止损距离
    期望_综合 = 胜率 * 总盈利 - 败率 * 止损距离
    
    print(f"{胜率_pct:.0f}%{'':<7} {期望_TP1:>+.3f}ATR{'':<6} {期望_TP2:>+.3f}ATR{'':<6} {期望_综合:>+.3f}ATR")

# 5. 吊灯止损分析
print("\n【五、吊灯止损机制】")
print(f"启动阈值: {config['吊灯止损启动阈值']}×ATR")
print(f"回撤阈值: {config['吊灯止损回撤阈值']}×ATR")
print("\n吊灯止损优势:")
print("  1. 盈利达到1.8×ATR后启动保护")
print("  2. 允许价格回撤1.2×ATR")
print("  3. 锁定部分盈利，避免盈利回吐")
print("  4. 在趋势行情中可以获得更大收益")

# 6. 风险控制机制
print("\n【六、风险控制机制】")
print("1. 分批止盈:")
print(f"   - TP1平仓{config['止盈TP1平仓比例']*100}%，锁定部分利润")
print(f"   - TP2平仓{config['止盈TP2平仓比例']*100}%，进一步锁定")
print(f"   - 剩余{config['剩余仓位比例']*100}%由吊灯止损保护")
print("\n2. 吊灯止损:")
print("   - 盈利1.8×ATR后启动")
print("   - 回撤1.2×ATR触发平仓")
print("   - 有效保护盈利")
print("\n3. 时间止损:")
print("   - 最大持仓72小时")
print("   - 超时平仓50%")
print("   - 避免资金长期占用")

# 7. 手续费影响
print("\n【七、手续费影响分析】")
开仓手续费 = 0.0004  # 0.04%
平仓手续费 = 0.0004  # 0.04%
总手续费率 = 开仓手续费 + 平仓手续费

print(f"开仓手续费: {开仓手续费*100:.2f}%")
print(f"平仓手续费: {平仓手续费*100:.2f}%")
print(f"总手续费: {总手续费率*100:.2f}%")

# 假设平均盈利2.5×ATR，ATR占价格约2%
平均盈利百分比 = 2.5 * 0.02
手续费占比 = 总手续费率 / 平均盈利百分比 * 100

print(f"\n假设ATR占价格2%:")
print(f"  平均盈利: {平均盈利百分比*100:.1f}%")
print(f"  手续费占比: {手续费占比:.1f}%")
print(f"  净盈利: {(平均盈利百分比 - 总手续费率)*100:.1f}%")

# 8. 总结
print("\n" + "="*70)
print("【总结】")
print("="*70)
print("\n✅ 策略优势:")
print(f"  1. 盈亏比合理: TP1={盈亏比_TP1:.2f}, TP2={盈亏比_TP2:.2f}, 综合={综合盈亏比:.2f}")
print(f"  2. 盈亏平衡胜率仅需: {1/(1+综合盈亏比)*100:.1f}%")
print(f"  3. 手续费影响小: 仅占盈利的{手续费占比:.1f}%")
print("  4. 多重保护: 分批止盈 + 吊灯止损 + 时间止损")

print("\n⚠️ 风险提示:")
print("  1. 如果胜率低于35%，策略可能亏损")
print("  2. 需要至少运行1-2周评估实际胜率")
print("  3. 市场震荡期可能频繁止损")
print("  4. 建议监控胜率和盈亏比，适时调整参数")

print("\n📊 建议监控指标:")
print("  1. 实际胜率（目标≥40%）")
print("  2. 平均盈利/平均亏损（目标≥1.5）")
print("  3. 最大回撤（目标≤10%）")
print("  4. 夏普比率（目标≥1.5）")

print("\n" + "="*70 + "\n")
