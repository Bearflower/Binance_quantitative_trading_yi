#!/bin/bash

# ============================================
# 上传脚本 - 使用 SSH 密钥认证
# ============================================

set -e

# 加载配置
source .deploy_config

echo "============================================="
echo "上传到服务器：$SERVER_IP"
echo "============================================="

# 检查压缩包是否存在
if [ ! -f "$DEPLOY_PACKAGE_NAME" ]; then
    echo "❌ 错误：压缩包不存在，请先执行打包"
    exit 1
fi

# 使用 SSH 别名上传
echo "🔑 使用 SSH 别名上传..."

# 使用配置的 SSH 别名
scp "$DEPLOY_PACKAGE_NAME" grid-signal-bot:/root/

echo "✅ 上传成功"
echo "============================================="
